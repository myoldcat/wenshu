def font(obj, size=10.5, bold=False, color='000000'):
    obj.font.name = 'Microsoft YaHei'
    obj.font.size = Pt(size)
    obj.font.bold = bold
    obj.font.color.rgb = RGBColor.from_string(color)
    pr = obj.element.get_or_add_rPr()
    rf = pr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts')
        pr.insert(0, rf)
    for key in ('ascii', 'hAnsi', 'eastAsia', 'cs'):
        rf.set(qn('w:' + key), 'Microsoft YaHei')
    for key in ('asciiTheme','hAnsiTheme','eastAsiaTheme','cstheme'):
        rf.attrib.pop(qn('w:' + key), None)

