def p(text, boldlead=None):
    para=doc.add_paragraph()
    if boldlead and text.startswith(boldlead):
        rr=para.add_run(boldlead); rr.bold=True
        para.add_run(text[len(boldlead):])
    else:
        para.add_run(text)
    return para

def h(text, level=2):
    return doc.add_paragraph(text, style=f'Heading {level}')

def page(title):
    doc.add_page_break()
    sections.append(title)
    h(title,1)

def req(code, title, text, source='已确认'):
    records.append({'id':code,'title':title,'source':source,'text':text})
    para=p(f'{code}  {title}  [{source}]')
    para.paragraph_format.keep_with_next=True
    para.paragraph_format.space_before=Pt(6)
    para.paragraph_format.space_after=Pt(2)
    for rr in para.runs:
        rr.bold=True
    p(text)

def table(headers, rows, widths):
    t=doc.add_table(rows=1, cols=len(headers))
    t.alignment=WD_TABLE_ALIGNMENT.CENTER
    t.autofit=False
    for col,w in zip(t.columns,widths): col.width=Mm(w)
    pr=t._tbl.tblPr
    borders=OxmlElement('w:tblBorders')
    for side in ['top','left','bottom','right','insideH','insideV']:
        b=OxmlElement('w:'+side)
        b.set(qn('w:val'),'single'); b.set(qn('w:sz'),'4'); b.set(qn('w:color'),'D9D9D9')
        borders.append(b)
    pr.append(borders)
    margins=OxmlElement('w:tblCellMar')
    for side in ['top','left','bottom','right']:
        item=OxmlElement('w:'+side)
        item.set(qn('w:w'),'95' if side in ['top','bottom'] else '115')
        item.set(qn('w:type'),'dxa'); margins.append(item)
    pr.append(margins)
    for j,label in enumerate(headers): t.rows[0].cells[j].text=label
    for row in rows:
        cells=t.add_row().cells
        for j,value in enumerate(row): cells[j].text=str(value)
    for i,row in enumerate(t.rows):
        rpr=row._tr.get_or_add_trPr()
        rpr.append(OxmlElement('w:cantSplit'))
        if i==0: rpr.append(OxmlElement('w:tblHeader'))
        for j,cell in enumerate(row.cells):
            cell.width=Mm(widths[j])
            cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            shd=OxmlElement('w:shd')
            shd.set(qn('w:fill'),'183349' if i==0 else ('F2F5F7' if i%2==0 else 'FFFFFF'))
            cell._tc.get_or_add_tcPr().append(shd)
            for para in cell.paragraphs:
                para.paragraph_format.space_before=Pt(0)
                para.paragraph_format.space_after=Pt(0)
                para.paragraph_format.line_spacing=1.12
                if widths[j] <= 24: para.alignment=WD_ALIGN_PARAGRAPH.CENTER
                for rr in para.runs: font(rr,9.2,i==0,'FFFFFF' if i==0 else '000000')
    gap=doc.add_paragraph()
    gap.paragraph_format.space_after=Pt(1)
    gap.paragraph_format.space_before=Pt(0)
    gap.paragraph_format.line_spacing=0.5
    return t

